/**
 * Render for injection into the composition prompt.
 *
 * NOTE: this used to default to 6, which silently dropped ten examples —
 * including every closing example. That is almost certainly why the trainer
 * kept scoring call-to-action at 3.8/10. All examples are sent now; the block
 * is ~2,200 tokens and sits in the cached part of the prompt.
 */
function render(limit = EXAMPLES.length) {
  const chosen = EXAMPLES.slice(0, limit);
  return `*דוגמאות לסגנון הנכון* — חקה את המבנה, הקצב והטון שלהן:

${chosen.map((ex, i) =>
  `דוגמה ${i + 1} (${ex.teaches})\n` +
  (ex.context ? `[הקשר: ${ex.context}]\n` : '') +
  `לקוח: "${ex.customer}"\n` +
  `תשובה נכונה:\n${ex.reply}`
).join('\n\n───\n\n')}

שים לב מה משותף לכולן: המשפט הראשון עונה על השאלה, יש התייחסות למה שהלקוח סיפר, אין הרצאות, ויש לכל היותר שאלה אחת בסוף.
וכשהשיחה מגיעה לסופה — היא תמיד נגמרת באותו מקום: *עו״ד פודים עצמו, ומועד קונקרטי.*`;
}

