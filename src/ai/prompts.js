function customerContext(profile, history = []) {
  const stageInfo = STAGES[profile.stage] || STAGES.NEW_LEAD;
  const missing = leadProfile.missingFacts(profile);
  const openObjections = (profile.objections || []).filter(o => !o.resolved).map(o => o.type);

  const lines = [
    `*מה שאנחנו כבר יודעים על הלקוח הזה:*`,
    leadProfile.summarise(profile),
    ``,
    `שלב במשפך: ${stageInfo.label} — המטרה כאן: ${stageInfo.goal}`,
    `מספר הודעות בשיחה: ${profile.messageCount || 0}`,
  ];

  if (profile.conversationSummary) {
    lines.push(``, `*סיכום השיחה עד כה:* ${profile.conversationSummary}`);
  }
  if (profile.questionsAsked?.length) {
    lines.push(`*נושאים שכבר עלו:* ${profile.questionsAsked.join(', ')} — אל תחזור עליהם`);
  }
  if (openObjections.length) {
    lines.push(`*התנגדויות פתוחות:* ${openObjections.join(', ')}`);
  }
  if (missing.length) {
    lines.push(`*מידע שעדיין חסר:* ${missing.join(', ')} — אבל אל תשאל יותר משאלה אחת`);
  }

  if (history.length) {
    lines.push(``, `*ההודעות האחרונות:*`);
    for (const m of history.slice(-8)) {
      lines.push(`${m.role === 'user' ? 'לקוח' : 'אנחנו'}: ${m.text}`);
    }
  }

  lines.push(
    ``,
    `⚠️ קריטי: אל תשאל דבר שכבר ידוע לך מהרשימה למעלה.`,
    `אם הלקוח כבר אמר ששנת הלידה 1927 — התייחס אליה, אל תשאל אותה שוב.`
  );

  return lines.join('\n');
}

