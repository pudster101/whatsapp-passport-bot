/**
 * Detect objections in free text. Returns an array of objection keys.
 *
 * Guarded: a question about eligibility, documents or process is a question,
 * not an objection, even when it happens to contain doubting words.
 */
const GENUINE_QUESTION = /זכא|זכאות|מגיע לי|מסמכ|תהליך|כמה זמן|איך מתחילים|מה צריך/;

function detect(text = '') {
  const lower = String(text).toLowerCase();
  const asksRealQuestion = GENUINE_QUESTION.test(lower);
  const found = [];

  for (const [key, obj] of Object.entries(OBJECTIONS)) {
    if (!obj.phrases.some(p => hasPhrase(lower, p.toLowerCase()))) continue;

    // These two fire on generic doubt words about US; suppress them when the
    // customer is plainly asking about the process rather than doubting us.
    // doubt_eligibility is deliberately NOT suppressed — its phrases are
    // specific ("אני לא בטוח שאני זכאי") and that IS the objection.
    if (asksRealQuestion && ['distrust', 'scam_worry'].includes(key)) {
      continue;
    }
    found.push(key);
  }
  return found;
}

function respond(key) {
  return OBJECTIONS[key]?.response || null;
}

function label(key) {
  return OBJECTIONS[key]?.label || key;
}

function list() {
  return Object.keys(OBJECTIONS);
}

module.exports = { OBJECTIONS, detect, respond, label, list };
